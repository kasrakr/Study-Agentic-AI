export function translate(key: string, locale: Locale): string {
  return locale === "fa" ? fa[key] ?? key : key;
}

interface LanguageContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
}
const LanguageContext = createContext<LanguageContextValue>({
  locale: "en", setLocale: () => {}, t: (key) => key,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    try { return window.localStorage.getItem(STORAGE_KEY) === "fa" ? "fa" : "en"; }
    catch { return "en"; }
  });

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "fa" ? "rtl" : "ltr";
    document.documentElement.dataset.locale = locale;
    document.title = locale === "fa" ? "دستیار مطالعه" : "Study Agent";
    try { window.localStorage.setItem(STORAGE_KEY, locale); } catch { /* private browsing */ }
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t: (key: string) => translate(key, locale) }), [locale]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useTranslation(): LanguageContextValue {
  return useContext(LanguageContext);
}
